def _package(name, first):
    """The eight fields at the top of a package card, keys t<first>..t<first+7>."""
    return {f"t{first + i}": f"{name}: {part}" for i, part in enumerate(PACKAGE_PARTS)}


def _steps(first, n=5):
    """Process steps: heading and text for each, keys t<first>, t<first+1>, ..."""
    out = {}
    for i in range(n):
        out[f"t{first + 2 * i}"] = f"Steg {i + 1}: rubrik"
        out[f"t{first + 2 * i + 1}"] = f"Steg {i + 1}: text"
    return out


